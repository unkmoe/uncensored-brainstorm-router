/**
 * Simplified-Chinese-intrusion detector for uncensored-backend responses.
 * Run: npx tsx calibration/detect-simplified.ts [--selftest | <file> | -]  (no arg = stdin)
 *
 * Design note: a naive first-pass scanner flagged normal Japanese text because its
 * character set mixed in Japanese common kanji (万・体 等) that merely *look* simplified. This detector uses a
 * curated set of **simplified-Chinese-specific characters only**: each char below is
 * absent from JIS X 0208/0213 (verified programmatically via Shift-JIS 2004
 * encodability), i.e. it cannot be part of standard written Japanese. Any hit is a
 * genuine simplified-Chinese intrusion signal, not a false positive on daily kanji.
 */

/**
 * Simplified-only code points. Generated by filtering a top-frequency simplified-Chinese
 * character list down to those NOT encodable in Shift-JIS 2004 (= absent from JIS X 0208+0213,
 * so impossible in standard written Japanese). Regenerate:
 *   python3 -c "... for ch in cands:\n  try: ch.encode('shift_jis_2004')\n  except UnicodeEncodeError: print(ch, end='')"
 */
const SIMPLIFIED_ONLY = new Set(
	"爱们这为时对发动过说产经进电实现线质强际样应该觉认话问题结验组织济观设计让记录检查试测请谢买卖读书习单风飞马鸟龙卫团场块处备头妇库务权标识馆饭饮驱骗鸡两严举义乡办汉亿仅仑仓仪伟传伤伦佣员东丝丧临乐亏亚亲亵伪"
);

export interface SimplifiedHit {
	/** 1-based line number. */
	line: number;
	/** The offending simplified-only characters found on that line. */
	chars: string[];
}

export function detectSimplified(text: string): SimplifiedHit[] {
	const hits: SimplifiedHit[] = [];
	const lines = text.split(/\r?\n/);
	for (let i = 0; i < lines.length; i++) {
		const chars = [...lines[i]].filter((c) => SIMPLIFIED_ONLY.has(c));
		if (chars.length > 0) hits.push({ line: i + 1, chars: [...new Set(chars)] });
	}
	return hits;
}

// ---------------------------------------------------------------------------
// Self-test: simplified intrusion must be detected; normal Japanese — including
// the 万/体-class kanji that caused the q1 false positives — must NOT be.
// ---------------------------------------------------------------------------

function selftest(): boolean {
	const cases: { name: string; text: string; expectHit: boolean }[] = [
		{
			name: "simplified intrusion in Japanese text",
			text: "終身雇用について考えます。这个问题很复杂，我们需要认真讨论。",
			expectHit: true,
		},
		{
			name: "pure simplified Chinese",
			text: "这是一个测试句子，用于检查简体中文的混入。",
			expectHit: true,
		},
		{
			name: "normal Japanese with look-alike common kanji (old false-positive class)",
			text: "万の一の場合でも、体調や会計の実績に問題はない。組織や観測も正常で、設計・認識・軽率な判断もしていない。",
			expectHit: false,
		},
		{
			name: "plain Japanese brainstorm answer",
			text: "遠慮のないブレストパートナーとして、感情労働の全面代替を論じます。失業リスクとスキル喪失の両面から検討しましょう。",
			expectHit: false,
		},
	];
	let pass = 0;
	for (const c of cases) {
		const hits = detectSimplified(c.text);
		const ok = hits.length > 0 === c.expectHit;
		if (ok) pass++;
		console.log(`${ok ? "PASS" : "FAIL"}  ${c.name}  (hits: ${hits.length ? hits.map((h) => `L${h.line}:${h.chars.join("")}`).join(", ") : "none"})`);
	}
	console.log(`\n${pass}/${cases.length} selftest cases passed`);
	return pass === cases.length;
}

// ---------------------------------------------------------------------------
// CLI
// ---------------------------------------------------------------------------

const args = process.argv.slice(2);
if (args.includes("--selftest")) {
	process.exit(selftest() ? 0 : 1);
} else {
	const input = args[0]
		? (args[0] === "-" ? await new Response(process.stdin).text() : await (await import("node:fs")).promises.readFile(args[0], "utf8"))
		: await new Response(process.stdin).text();
	const hits = detectSimplified(input);
	if (hits.length === 0) {
		console.log("OK: no simplified-Chinese-specific characters found");
	} else {
		console.log(`FOUND simplified-Chinese-specific characters on ${hits.length} line(s):`);
		for (const h of hits) console.log(`  line ${h.line}: ${h.chars.join(" ")}`);
		process.exit(1);
	}
}
